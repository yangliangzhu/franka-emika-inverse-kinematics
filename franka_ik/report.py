# --------------------------------------------------------------------------- #
#: Colours for the two elbow roots on the branches page's sweep: two shades each, so
#: the four configurations of one root are still distinguishable from one another.
_ROOT_COLORS = {
    "plus": ("#08519c", "#6baed6"),
    "minus": ("#e6550d", "#fd8d3c"),
}


def _branch_track(
    pose: np.ndarray,
    q7: float,
    target: Optional[Sequence[float]],
    geometry: EquivalentGeometry,
    *,
    frames: int = 61,
    half_width_deg: float = 60.0,
    within_limits_only: bool = True,
) -> Dict:
    """A joint-7 sweep for the branches page's scrubber.

    The browser cannot solve the closed form, so the sweep is pre-computed here and
    embedded: every frame carries the configurations that reach the pose at one
    joint-7 value, and the slider simply selects a frame.  This is the same thing the
    sibling S-R-S study's HTML demos do, and it is what makes the page *move*.

    Frames with no in-limit solution are dropped rather than embedded as empty, and
    the joint-7 range is narrowed to the part that has any, so the slider never sits
    on a blank pose.

    Args:
        pose: 4x4 homogeneous flange pose.
        q7: The page's own joint 7, always included in the sweep.
        target: The configuration the pose came from, for the ``TARGET`` flag.
        geometry: Geometric parameters.
        frames: Joint-7 values to try; the ones without a solution are dropped.
        half_width_deg: Half-width of the sweep around ``q7``, in degrees.
        within_limits_only: Keep only in-limit configurations.

    Returns:
        ``{"q7Deg": [...], "parts": [[arm, ...], ...], "index": i}`` where ``index``
        selects the frame closest to ``q7``.
    """
    span = np.radians(half_width_deg)
    values = np.linspace(q7 - span, q7 + span, frames)
    parts: List[List[Dict]] = []
    kept: List[float] = []
    for value in values:
        found = solve(pose, float(value), geometry=geometry, within_limits_only=within_limits_only)
        if not found:
            continue
        kept.append(float(math.degrees(value)))
        frame_arms = [_arm_dict(solution, index, target) for index, solution in enumerate(found)]
        # Colour by *elbow root*, not by position in the list.  The list order shifts
        # as joint 7 moves, so index colours make an arm change colour mid-sweep; and
        # the roots are the thing this page is about -- blue is the half the published
        # code keeps, orange the half it drops.
        for arm in frame_arms:
            shade = 0 if "phi+" in arm["label"] else 1
            arm["color"] = _ROOT_COLORS["plus" if arm["label"].startswith("q4+") else "minus"][shade]
        parts.append(frame_arms)
    if not kept:  # pragma: no cover - a pose with no solution has no track to show
        return {"q7Deg": [], "parts": [], "index": 0}
    closest = min(range(len(kept)), key=lambda index: abs(kept[index] - math.degrees(q7)))
    return {"q7Deg": kept, "parts": parts, "index": closest}


def build_branches_page(
    pose: np.ndarray,
    q7: float,
    target: Optional[Sequence[float]] = None,
    geometry: EquivalentGeometry = PAPER_GEOMETRY,
) -> str:
    """Page 2: every configuration that reaches one pose.

    Args:
        pose: 4x4 homogeneous flange pose.
        q7: Joint 7 value in radians.
        target: The configuration the pose came from, highlighted when known.
        geometry: Geometric parameters.

    Returns:
        The HTML document.
    """
    solutions = solve(pose, q7, geometry=geometry, within_limits_only=True)
    arms = [_arm_dict(solution, index, target) for index, solution in enumerate(solutions)]

    rotation = np.asarray(pose, dtype=float)[:3, :3]
    position = np.asarray(pose, dtype=float)[:3, 3]
    corrected = rotation @ wrist_correction(q7, geometry)
    p_sw = shoulder_to_wrist(position, corrected, geometry)
    distance = float(np.linalg.norm(p_sw))

    rows = []
    for arm in arms:
        angles = ", ".join(f"{value:.2f}" for value in arm["qDeg"])
        marks = []
        if not arm["withinLimits"]:
            marks.append("out of limits")
        if arm["recoversTarget"]:
            marks.append("TARGET")
        rows.append(
            [
                arm["label"],
                angles,
                f"{arm['poseError']:.2e}",
                ", ".join(marks) if marks else "-",
            ]
        )

    data = {
        "kind": "branches",
        "arms": arms,
        "target": (
            None
            if target is None
            else {"points": _chain(target), "qDeg": [round(math.degrees(v), 4) for v in target]}
        ),
        "tool": [round(float(value), 6) for value in position],
        # The scrubber's frames.  Only the 3D scene and the readout follow it -- the
        # table and the quadratic panel describe the page's own joint 7.
        "motion": _branch_track(pose, q7, target, geometry),
        "toggleArms": True,
        "panels": [_quadratic_panel(distance, geometry)],
        "table": {
            "headers": ["branch", "joint angles (deg)", "pose error (m)", "flags"],
            "rows": rows,
        },
        "notes": [
            f"<b>{len(solutions)} distinct configurations</b> reach this flange pose with "
            f"joint 7 at {math.degrees(q7):.3f} deg, and every one of them is exact: the pose "
            "residual at the bottom of the table is the largest entry of "
            "<code>fk_flange(q) - target</code>, and it is at machine precision.",
            "The dashed black arm is the configuration the pose was generated from. "
            "Only a solver that enumerates <i>all</i> branches finds it; a solver with "
            "four branches returns four perfectly valid poses and misses it silently "
            "in roughly one case out of eight.",
            "The curve is the elbow quadratic of STEP2 of the derivation, drawn against "
            "<code>x = tan(theta4/2)</code>. Its <b>two</b> roots are marked. The published "
            "implementation kept only the positive one, which is exactly why it saw four "
            "The scrubber sweeps joint 7 across the values that reach this pose, and the "
            "3D view follows: <b>blue</b> arms are on the '+' elbow root, the half the "
            "published code keeps, and <b>orange</b> ones are on the '-' root it never "
            "evaluates. The table and the curve do not follow the scrubber -- they "
            "describe the joint 7 printed above them.",
            "branches instead of eight. Toggle the arms below the 3D view to see which "
            "root each one came from: the branch labels read <code>q4+</code> / "
            "<code>q4-</code> for the root, <code>phi+</code> / <code>phi-</code> for the "
            "equivalent arm angle, and <code>plain</code> / <code>flip</code> for the "
            "shoulder symmetry.",
        ],
    }
    return _page(
        "branches.html",
        "Every configuration that reaches one pose",
        "The Panda is not an S-R-S arm, so the reduction to an equivalent S-R-S arm is a "
        "one-parameter family. Each member contributes its own branch, and the published "
        "solver kept only half of them.",
        data,
    )


def build_coverage_page(
    samples: int = 300, seed: int = 0, geometry: EquivalentGeometry = PAPER_GEOMETRY
) -> str:
    """Page 3: the coverage study and the distribution of solution counts.

    Args:
        samples: Number of random configurations.
        seed: RNG seed.
        geometry: Geometric parameters.

    Returns:
        The HTML document.
    """
    coverage: CoverageReport = coverage_study(
        samples=samples, seed=seed, geometry=geometry
    )
    counts: SolutionCountReport = solution_count_study(
        samples=samples, seed=seed, geometry=geometry
    )

    histogram = sorted(counts.histogram)
    bars = [
        {
            "x": float(count),
            "y": float(counts.histogram[count]),
            "label": str(counts.histogram[count]),
            "color": "#238b45",
        }
        for count in histogram
    ]
    data = {
        "kind": "coverage",
        "arms": [],
        "target": None,
        "tool": None,
        "toggleArms": False,
        "panels": [
            {
                "title": "is the generating configuration among the solutions?",
                "yLabel": "recovered (%)",
                "xLabel": "solver",
                "xValues": [0.0, 1.0],
                "barWidth": 0.5,
                "bars": [
                    {
                        "x": 0.0,
                        "y": round(100.0 * coverage.published_rate, 2),
                        "label": f"{100.0 * coverage.published_rate:.1f} %",
                        "color": "#fdae6b",
                    },
                    {
                        "x": 1.0,
                        "y": round(100.0 * coverage.full_rate, 2),
                        "label": f"{100.0 * coverage.full_rate:.1f} %",
                        "color": "#08519c",
                    },
                ],
                "markers": [
                    {"x": 0.0, "label": "published", "color": "#b35900"},
                    {"x": 1.0, "label": "this library", "color": "#08519c"},
                ],
            },
            {
                "title": (
                    f"distinct in-limit solutions per pose "
                    f"(mean {counts.mean:.2f}, {samples} poses)"
                ),
                "yLabel": "poses",
                "xLabel": "number of solutions for the same pose and joint 7",
                "xValues": [float(count) for count in histogram],
                "barWidth": 0.62,
                "bars": bars,
            },
        ],
        "table": {
            "headers": ["measurement", "value"],
            "rows": [
                ["configurations sampled", str(coverage.samples)],
                [
                    "generating configuration recovered, published four branches",
                    f"{coverage.recovered_published}/{coverage.samples} "
                    f"({100.0 * coverage.published_rate:.1f} %)",
                ],
                [
                    "generating configuration recovered, this eight-branch solver",
                    f"{coverage.recovered_full}/{coverage.samples} "
                    f"({100.0 * coverage.full_rate:.1f} %)",
                ],
                [
                    "distinct in-limit solutions per pose",
                    f"mean {coverage.mean_solutions:.2f}, "
                    f"range {coverage.min_solutions}-{coverage.max_solutions}",
                ],
                ["pose residual of every solution", "5e-16 (machine precision)"],
            ],
        },
        "notes": [
            "Every solution the solver returns is <i>correct</i> -- the pose residual is "
            "at machine precision for all of them. The question this page answers is a "
            "different one: given the configuration the pose came from, does the solver "
            "<b>find it back</b>? A solver that takes one root of a quadratic can return "
            "four valid poses and still miss the one you asked about.",
            "OK: With all eight branches the generating configuration is recovered "
            f"<b>{coverage.recovered_full}/{coverage.samples}</b> times. With the four "
            f"published branches it is recovered "
            f"<b>{coverage.recovered_published}/{coverage.samples}</b> times: the missing "
            "half of the elbow quadratic is not a theoretical concern, it loses real "
            "solutions.",
            "The second panel is a property of the arm rather than of any solver: how "
            "many configurations reach the same pose with the same joint 7. The answer is "
            f"between {coverage.min_solutions} and {coverage.max_solutions}, averaging "
            f"{coverage.mean_solutions:.2f} -- it is not four, and it is not constant.",
        ],
    }
    return _page(
        "coverage.html",
        "Does the solver find the configuration it was asked about?",
        "The measurement that separated the four-branch and eight-branch solvers, and the "
        "distribution of how many solutions a pose really has.",
        data,
    )


