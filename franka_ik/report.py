def _chain(q: Sequence[float]) -> List[List[float]]:
    """Joint origins of a configuration plus the flange, rounded for embedding."""
    frames = model.forward_kinematics(q)
    points = [[0.0, 0.0, 0.0]]
    points.extend(
        [float(value) for value in frames[index][:3, 3]] for index in range(model.NUM_JOINTS)
    )
    points.append([float(value) for value in frames[model.FLANGE_ROW][:3, 3]])
    return [[round(value, 6) for value in point] for point in points]


def _arm_dict(solution: IkSolution, index: int, target: Optional[Sequence[float]]) -> Dict:
    """One arm entry of the 3D scene."""
    recovers = False
    if target is not None:
        delta = solution.q - np.asarray(target, dtype=float)
        recovers = bool(np.all(np.abs(np.arctan2(np.sin(delta), np.cos(delta))) < 1e-6))
    return {
        "label": solution.label,
        "color": BRANCH_COLORS[index % len(BRANCH_COLORS)],
        "points": _chain(solution.q),
        "qDeg": [round(math.degrees(value), 4) for value in solution.q],
        "poseError": float(solution.pose_error),
        "withinLimits": bool(solution.within_limits),
        "recoversTarget": recovers,
    }


def _quadratic_panel(
    distance: float, geometry: EquivalentGeometry, samples: int = 401
) -> Dict:
    """Panel data for the STEP2 elbow quadratic, with both roots marked."""
    a2, a1, a0 = q4_coefficients(distance**2, geometry)
    roots = q4_roots(distance**2, geometry)
    scale = max(abs(a2), abs(a1), abs(a0), 1e-9)

    limit = 6.0
    xs = np.linspace(-limit, limit, samples)
    values = (a2 * xs**2 - a1 * xs + a0) / scale

    markers = []
    off_scale = []
    for index, theta4 in enumerate(roots):
        abscissa = math.tan(theta4 / 2.0)
        label = f"theta4 = {math.degrees(theta4):.2f} deg"
        if abs(abscissa) > limit:
            # theta4 approaching +-180 deg sends x = tan(theta4/2) to infinity;
            # the marker is pinned to the edge and the value is named instead.
            abscissa = math.copysign(limit, abscissa)
            label += " (off scale)"
            off_scale.append(math.degrees(theta4))
        markers.append(
            {
                "x": float(abscissa),
                "label": label,
                "color": ["#cb181d", "#238b45"][index % 2],
            }
        )
    title = (
        f"elbow quadratic at |x_sw| = {distance:.4f} m   "
        f"(discriminant {q4_discriminant(distance**2, geometry):+.4e})"
    )
    if off_scale:
        title += (
            "   --  root near theta4 = "
            + ", ".join(f"{value:.2f}" for value in off_scale)
            + " deg lies beyond the drawn range of tan(theta4/2)"
        )
    return {
        "title": title,
        "yLabel": "normalised",
        "xLabel": "x = tan(theta4 / 2)",
        "xValues": [round(float(value), 5) for value in xs],
        "series": [
            {
                "label": "a2 x^2 - a1 x + a0",
                "values": [round(float(value), 8) for value in values],
                "color": "#08519c",
                "width": 2.0,
            }
        ],
        "markers": markers,
    }


