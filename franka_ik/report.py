_ASSET_DIR = Path(__file__).resolve().parent / "web"

#: Pages of the generated site, as ``(file name, navigation label)``.
PAGES: Tuple[Tuple[str, str], ...] = (
    ("index.html", "overview"),
    ("branches.html", "solution branches"),
    ("coverage.html", "coverage study"),
)


def _read_asset(name: str) -> str:
    """Read a file from ``franka_ik/web``."""
    path = _ASSET_DIR / name
    if not path.is_file():
        raise FileNotFoundError(
            f"missing web asset {path}; reinstall so that franka_ik/web ships as package data"
        )
    return path.read_text(encoding="utf-8")


def _nav(current: str) -> str:
    """Navigation bar, with the current page marked."""
    links = []
    for file_name, label in PAGES:
        css = ' class="current"' if file_name == current else ""
        links.append(f'<a href="{file_name}"{css}>{label}</a>')
    return '<nav class="pages">' + "".join(links) + "</nav>"


