"""Self-contained interactive HTML reports.

Three pages, all single files with the CSS and JavaScript inlined: no CDN, no
build step, no network, so they open straight from the file system.

===================  ==========================================================
``index.html``        what the method is, and the two headline measurements
``branches.html``     every configuration that reaches one pose, drawn on top of
                      each other, with the elbow quadratic that produces them
``coverage.html``     does the solver find the configuration the pose came from?
===================  ==========================================================

All the geometry and arithmetic happens in Python; the page embeds the computed
arrays and inlines ``franka_ik/web/demo.js``, which only draws them.  Nothing is
recomputed in the browser, so what a reader sees is what the tests assert.
"""

