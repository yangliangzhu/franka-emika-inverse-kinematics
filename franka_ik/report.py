def build_demo_site(
    out_dir: Union[str, Path] = "demos",
    samples: int = 300,
    seed: int = 0,
    geometry: EquivalentGeometry = PAPER_GEOMETRY,
    rich_min_solutions: int = 6,
) -> List[Path]:
    """Generate the whole interactive report site.

    Args:
        out_dir: Directory to write into; created if missing.
        samples: Number of random configurations for the studies.
        seed: RNG seed.
        geometry: Geometric parameters.
        rich_min_solutions: How many solutions the pose on the branch page should
            have, so that the drawing is informative.

    Returns:
        The files written, ``index.html`` first.
    """
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    rng = np.random.default_rng(seed)
    lower, upper = model.lower_limits(), model.upper_limits()

    # Pick a pose for the branch page that actually *has* several solutions: a
    # randomly chosen configuration often has only two, which makes for a dull
    # picture.  Draw candidates until one has at least `rich_min_solutions`.
    target, pose, rich = None, None, 0
    for _ in range(400):
        candidate = rng.uniform(lower, upper)
        candidate_pose = model.fk_flange(candidate)
        count = len(
            solve(
                candidate_pose,
                float(candidate[6]),
                geometry=geometry,
                within_limits_only=True,
            )
        )
        if count > rich:
            target, pose, rich = candidate, candidate_pose, count
        if rich >= rich_min_solutions:
            break
    assert target is not None and pose is not None

    pages = [
        ("index.html", build_index_page(samples, seed, geometry)),
        (
            "branches.html",
            build_branches_page(pose, float(target[6]), target, geometry),
        ),
        ("coverage.html", build_coverage_page(samples, seed, geometry)),
    ]

    written = []
    for file_name, html in pages:
        path = out_dir / file_name
        path.write_text(html, encoding="utf-8")
        written.append(path)
    return written
